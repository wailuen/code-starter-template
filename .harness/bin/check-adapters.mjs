#!/usr/bin/env node
// Adapter content is mechanical; policy lives in shared phases, guides and roles.
//
//   node .harness/bin/check-adapters.mjs           # report drift (exit 1 on any)
//   node .harness/bin/check-adapters.mjs --write   # regenerate every enabled adapter file
//   node .harness/bin/check-adapters.mjs --write --codex   # also enable + generate Codex adapters
//   node .harness/bin/check-adapters.mjs --write --codex-only # never write Claude files
//
// Exit: 0 every adapter matches · 1 drift (or invalid manifest) · 2 usage error.
//
// Claude Code adapters (`.claude/commands/<phase>.md`) are always checked. Codex adapters
// (`.agents/skills/`, `.codex/agents/`) are checked only once the project has enabled Codex,
// i.e. once either directory exists, or when explicitly requested with --codex/--codex-only.
//
// Stray files: when Codex adapters are checked, a file the renderer no longer produces but whose
// text is EXACTLY this generator's template for its name — `.codex/agents/harness-<role>.toml` or
// `.agents/skills/<name>/SKILL.md`, with only the description, model, effort and instruction-path
// values free — is drift (a stale agent is still offered to Codex); `--write` deletes it. Any
// other file in those directories (a project's own skill, even one that cites the Codex adapter)
// is listed as "not generated by the harness", left alone, and never fails the check.
//
// `--write` checks every target before writing anything: a target that is, or sits under, a
// symlink leaving the repository is refused ("Refusing to write ...") and nothing is written.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, realpathSync, lstatSync, unlinkSync, rmdirSync, constants } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname, relative, isAbsolute, sep } from "node:path";
export const root = fileURLToPath(new URL("../../", import.meta.url));
// Phase, helper and agent names become path segments: lowercase words joined by hyphens, never
// `..`, `/` or anything else that could move a generated file outside its directory.
const validName = (name) => /^[a-z][a-z0-9-]*$/.test(name);
// Reasoning-effort values this manifest uses and that the Codex configuration reference
// documents for `model_reasoning_effort`. Add a value only after confirming it there; the list
// exists to fail closed on a typo, so an unverified value defeats it.
export const CODEX_EFFORTS = ["low", "medium", "high", "xhigh"];
// The generator's templates. Every adapter file is rendered from these, and stale-file detection
// compares a leftover file against the same text.
const phaseSkill = (phase, description) => `---\nname: ${phase}\ndescription: ${description}\n---\n\nRead and follow the repository's \`.harness/adapters/codex.md\`, then\n\`.harness/phases/${phase}.md\` in full. Resolve paths from the Git repository root.\nTreat \`$ARGUMENTS\` in the shared procedure as the user's phase arguments.\nDo not copy policy here; edit the shared files so both runtimes benefit.\n`;
const helperSkill = (name, description) => `---\nname: ${name}\ndescription: ${description}\n---\n\nRead and follow the repository's \`.harness/adapters/codex.md\`, then\n\`.claude/commands/${name}.md\` in full as a read-only instruction source.\nResolve paths from the repository root. Treat \`$ARGUMENTS\` as the user's arguments.\nMap Claude tool and agent names through the Codex adapter; never execute a slash command in a shell.\nDo not edit this generated wrapper.\n`;
const agentInstructions = (path) => `Read .harness/adapters/codex.md in full, then ${path}. From .harness/guides/task-delivery.md read only the sections that file or your brief names (at least § Workspace file layout).\nThe Codex adapter owns runtime mapping. Ignore Claude frontmatter model, effort and tools; follow the instruction body.\nBefore any checkout-dependent action, enter the assigned absolute checkout and verify its resolved root and expected revision. Stop on mismatch.\nUse absolute paths or an explicit workdir on every tool call; a previous shell cd does not persist.\nStay within the assigned scope. Reviewers report without editing the author's checkout. Return evidence, actual checks and unresolved items; never an unsupported CLEAR.\n`;
const agentToml = (role, description, model, effort, instructions) => `name = "harness-${role}"\ndescription = ${description}\nmodel = ${model}\nmodel_reasoning_effort = ${effort}\ndeveloper_instructions = ${instructions}\n`;

// A template with its free values as patterns: SLOT stands for a whole JSON string, PATH_SLOT for
// text inside one. Everything else must match byte for byte.
const SLOT = "\u0000SLOT\u0000", PATH_SLOT = "\u0000PATH\u0000";
const reEscape = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const templatePattern = (text) => new RegExp(`^${reEscape(text)
  .replaceAll(reEscape(SLOT), '"(?:[^"\\\\]|\\\\.)*"').replaceAll(reEscape(PATH_SLOT), '(?:[^"\\\\]|\\\\.)*?')}$`);
function isGeneratedSkill(name, text) {
  return templatePattern(phaseSkill(name, SLOT)).test(text) || templatePattern(helperSkill(name, SLOT)).test(text);
}
function isGeneratedAgent(role, text) {
  const instructions = JSON.stringify(agentInstructions(PATH_SLOT)).replace(JSON.stringify(PATH_SLOT).slice(1, -1), PATH_SLOT);
  return templatePattern(agentToml(role, SLOT, SLOT, SLOT, instructions)).test(text);
}
export function codexEnabled(base = root) {
  return existsSync(resolve(base, ".agents")) || existsSync(resolve(base, ".codex"));
}
export function renderAdapters({ codex = true } = {}) {
  const manifest = JSON.parse(readFileSync(resolve(root, ".harness/manifest.json"), "utf8"));
  const files = {};
  for (const [phase, description] of Object.entries(manifest.phases)) {
    if (!validName(phase) || typeof description !== "string") throw new Error(`Invalid phase: ${phase}`);
    if (codex) files[`.agents/skills/${phase}/SKILL.md`] = phaseSkill(phase, JSON.stringify(description));
    files[`.claude/commands/${phase}.md`] = `---\nname: ${phase}\ndescription: ${JSON.stringify(description)}\n---\n\nRead and follow \`.harness/adapters/claude.md\`, then \`.harness/phases/${phase}.md\` in full.\nTreat \`$ARGUMENTS\` as the user's phase arguments. Do not copy policy here.\n`;
  }
  if (codex) {
    const settings = manifest.codex;
    if (!settings?.agents || !settings?.helpers) throw new Error("Missing manifest.codex agents/helpers");
    for (const [name, description] of Object.entries(settings.helpers)) {
      if (!validName(name) || Object.hasOwn(manifest.phases, name) || typeof description !== "string")
        throw new Error(`Invalid Codex helper: ${name}`);
      files[`.agents/skills/${name}/SKILL.md`] = helperSkill(name, JSON.stringify(description + ` Use for $${name} or /${name}.`));
    }
    for (const [role, agent] of Object.entries(settings.agents)) {
      if (!validName(role) || !agent ||
          ![agent.description, agent.instructions, agent.model].every(v => typeof v === "string" && v.trim()) ||
          !CODEX_EFFORTS.includes(agent.model_reasoning_effort))
        throw new Error(`Invalid Codex agent settings: ${role}`);
      files[`.codex/agents/harness-${role}.toml`] = agentToml(role, JSON.stringify(agent.description), JSON.stringify(agent.model),
        JSON.stringify(agent.model_reasoning_effort), JSON.stringify(agentInstructions(agent.instructions)));
    }
  }
  return files;
}
// Generated files the renderer no longer produces, and unmanaged files beside them.
export function strayAdapterFiles(rendered, base = root) {
  const stray = [], unmanaged = [];
  const list = (dir) => { try { return readdirSync(resolve(base, dir), { withFileTypes: true }); } catch { return []; } };
  for (const e of list(".agents/skills")) {
    const path = `.agents/skills/${e.name}/SKILL.md`;
    if (!e.isDirectory()) { unmanaged.push(`.agents/skills/${e.name}`); continue; }
    if (Object.hasOwn(rendered, path)) continue;
    let text = null; try { text = readFileSync(resolve(base, path), "utf8"); } catch { /* no SKILL.md: not ours */ }
    (text !== null && isGeneratedSkill(e.name, text) ? stray : unmanaged).push(path);
  }
  for (const e of list(".codex/agents")) {
    const path = `.codex/agents/${e.name}`;
    if (Object.hasOwn(rendered, path)) continue;
    const role = e.name.match(/^harness-(.+)\.toml$/)?.[1];
    let text = null; try { text = readFileSync(resolve(base, path), "utf8"); } catch { /* unreadable: not ours */ }
    (role && text !== null && isGeneratedAgent(role, text) ? stray : unmanaged).push(path);
  }
  return { stray, unmanaged };
}

// A generated path must land inside this repository even if a directory on the way is a
// symlink: the nearest existing ancestor is resolved through realpath and compared with the
// real root, and the final open refuses to follow a symlink (O_NOFOLLOW).
function containedTarget(path) {
  const target = resolve(root, path);
  const lexical = relative(root, target);
  if (!lexical || lexical.startsWith("..") || isAbsolute(lexical)) throw new Error(`Refusing to write outside the repository: ${path}`);
  const realRoot = realpathSync(root);
  let dir = dirname(target);
  while (!existsSync(dir)) dir = dirname(dir);
  const realDir = realpathSync(dir);
  if (realDir !== realRoot && !realDir.startsWith(realRoot + sep)) throw new Error(`Refusing to write through a symlink that leaves the repository: ${path}`);
  return target;
}
// Checked for EVERY target before anything is written or deleted, so a refusal leaves the
// tree as it was rather than half-regenerated.
function assertNotSymlink(path) {
  const target = containedTarget(path);
  let link = false;
  try { link = lstatSync(target).isSymbolicLink(); } catch { /* absent: will be created */ }
  if (link) throw new Error(`Refusing to write through a symlink: ${path}`);
  return target;
}
function writeContained(path, text) {
  const target = containedTarget(path);
  mkdirSync(dirname(target), { recursive: true });
  containedTarget(path); // re-check now that every directory on the way exists
  try {
    // O_NOFOLLOW at the sink: a symlink swapped in after the check above is still refused.
    writeFileSync(target, text, { flag: constants.O_WRONLY | constants.O_CREAT | constants.O_TRUNC | (constants.O_NOFOLLOW || 0) });
  } catch (error) {
    if (error.code === "ELOOP") throw new Error(`Refusing to write through a symlink: ${path}`);
    throw error;
  }
}

// Symlink-safe: compare real paths on both sides, or a call through a symlinked directory
// (macOS /tmp, a linked worktree) would silently skip the check and exit 0.
const invokedPath = process.argv[1] ? (() => { try { return realpathSync(process.argv[1]); } catch { return null; } })() : null;
if (invokedPath && invokedPath === realpathSync(fileURLToPath(import.meta.url))) {
  const args = process.argv.slice(2);
  const unknown = args.filter((a) => !["--write", "--codex", "--codex-only"].includes(a));
  if (unknown.length) {
    console.error(`Unknown argument(s): ${unknown.join(" ")}\nUsage: check-adapters.mjs [--write] [--codex | --codex-only]`);
    process.exit(2);
  }
  const write = args.includes("--write");
  const codexOnly = args.includes("--codex-only");
  const codex = codexOnly || args.includes("--codex") || codexEnabled();
  let failures = 0;
  try {
    const rendered = renderAdapters({ codex });
    const adapters = Object.fromEntries(Object.entries(rendered)
      .filter(([path]) => !codexOnly || !path.startsWith(".claude/")));
    const { stray, unmanaged } = codex ? strayAdapterFiles(rendered) : { stray: [], unmanaged: [] };
    if (write) for (const path of [...Object.keys(adapters), ...stray]) assertNotSymlink(path);
    for (const [path, expected] of Object.entries(adapters)) {
      let actual; try { actual = readFileSync(resolve(root, path), "utf8"); } catch { actual = null; }
      if (actual === expected) continue;
      if (write) {
        writeContained(path, expected);
        console.log(`Wrote ${path}`);
      } else { console.error(`Adapter drift: ${path}`); failures++; }
    }
    if (codex) {
      for (const path of stray) {
        if (write) {
          const target = containedTarget(path);
          if (lstatSync(target).isSymbolicLink()) throw new Error(`Refusing to write through a symlink: ${path}`);
          unlinkSync(target);
          if (path.startsWith(".agents/skills/")) { try { rmdirSync(dirname(target)); } catch { /* not empty: keep the project's other files */ } }
          console.log(`Removed stale generated ${path}`);
        } else { console.error(`Adapter drift: ${path} (stale generated file; the manifest no longer produces it)`); failures++; }
      }
      for (const path of unmanaged) console.error(`Note: ${path} is not generated by the harness; left alone.`);
    }
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
  if (failures) console.error(`Regenerate with \`node .harness/bin/check-adapters.mjs --write${codexOnly ? " --codex-only" : codex ? " --codex" : ""}\`; do not duplicate shared policy.`);
  else console.log(`Shared harness adapters match the manifest (${codexOnly ? "Codex only; Claude Code untouched" : codex ? "Claude Code + Codex" : "Claude Code only; Codex not enabled"}).`);
  process.exitCode = failures ? 1 : 0;
}
